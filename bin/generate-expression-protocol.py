#!/usr/bin/env python3
"""Generate Java/Rust expression tags from the unchanged compact expression protocol."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "native/engine/expression-protocol.json"
ENUMS = {"nodeKinds": "ExpressionKind", "castTargets": "CastTarget"}
CODES = {
    "certifiedOps": ("CertifiedOp", "certified_op"),
    "scalarOps": ("ScalarOp", "scalar_op"),
    "groupAggregateKinds": ("GroupAggregateKind", "group_aggregate_kind"),
    "windowAggregateKinds": ("WindowAggregateKind", "window_aggregate_kind"),
}


def validate(manifest):
    if manifest["version"] != 1:
        raise ValueError("Unsupported expression protocol version")
    for group in (*ENUMS, *CODES):
        entries = manifest[group]
        names = [entry["name"] for entry in entries]
        codes = [entry["code"] for entry in entries]
        if any(type(code) is not int or code < 0 for code in codes):
            raise ValueError(f"Invalid expression protocol code in {group}")
        if any(not isinstance(name, str) or re.fullmatch(r"[A-Z][A-Z0-9_]*", name) is None
               for name in names):
            raise ValueError(f"Invalid expression protocol name in {group}")
        if len(set(names)) != len(names) or len(set(codes)) != len(codes):
            raise ValueError(f"Duplicate expression protocol name or code in {group}")
    reserved = manifest["reservedNodeKinds"]
    if set(reserved) & {entry["code"] for entry in manifest["nodeKinds"]}:
        raise ValueError("A retired expression node kind was reused")


def java_enum(name, entries):
    values = ",\n".join(f"  {entry['name']}({entry['code']})" for entry in entries)
    cases = "\n".join(
        f"      case {entry['code']}: return {entry['name']};" for entry in entries)
    return f"""package tech.streamfusion.planner.common;

// Generated by bin/generate-expression-protocol.py; edit native/engine/expression-protocol.json.
public enum {name} {{
{values};

  private final int code;

  {name}(int code) {{
    this.code = code;
  }}

  public int code() {{ return code; }}

  public static {name} fromCode(int code) {{
    switch (code) {{
{cases}
      default: throw new IllegalArgumentException("Unknown {name} code: " + code);
    }}
  }}
}}
"""


def rust_name(name):
    return "".join(part.title() for part in name.split("_"))


def java_codes(name, entries):
    values = "\n".join(
        f"  public static final int {entry['name']} = {entry['code']};" for entry in entries)
    return f"""package tech.streamfusion.planner.common;

// Generated by bin/generate-expression-protocol.py; edit native/engine/expression-protocol.json.
public final class {name} {{
  private {name}() {{}}

{values}
}}
"""


def rust_codes(name, entries):
    values = "\n".join(
        f"    pub(crate) const {entry['name']}: i64 = {entry['code']};" for entry in entries)
    return f"""#[allow(dead_code)]
pub(crate) mod {name} {{
{values}
}}
"""


def rust_enum(name, entries):
    values = "\n".join(f"    {rust_name(entry['name'])} = {entry['code']}," for entry in entries)
    cases = "\n".join(
        f"            {entry['code']} => Self::{rust_name(entry['name'])}," for entry in entries)
    return f"""#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(i64)]
pub(crate) enum {name} {{
{values}
}}

impl {name} {{
    pub(crate) fn from_code(code: i64) -> Option<Self> {{
        Some(match code {{
{cases}
            _ => return None,
        }})
    }}
}}
"""


def render(manifest):
    validate(manifest)
    java_root = "streamfusion-core/src/main/java/tech/streamfusion/planner/common/"
    sources = {java_root + name + ".java": java_enum(name, manifest[group])
               for group, name in ENUMS.items()}
    sources.update({java_root + name + ".java": java_codes(name, manifest[group])
                    for group, (name, _) in CODES.items()})
    rust = [rust_enum(name, manifest[group]) for group, name in ENUMS.items()]
    rust.extend(rust_codes(name, manifest[group]) for group, (_, name) in CODES.items())
    sources["native/engine/src/expression_protocol.rs"] = (
        "// Generated by bin/generate-expression-protocol.py; edit expression-protocol.json.\n\n"
        + "\n".join(rust))
    return sources


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated sources are stale")
    options = parser.parse_args()
    generated = render(json.loads(MANIFEST.read_text()))
    stale = []
    for relative, content in generated.items():
        path = ROOT / relative
        if options.check:
            if not path.is_file() or path.read_text() != content:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, "Stale expression protocol sources: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
