package tech.streamfusion.operator;

import static org.junit.jupiter.api.Assertions.*;

import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;
import org.apache.flink.api.common.typeinfo.Types;
import org.apache.flink.runtime.checkpoint.OperatorSubtaskState;
import org.apache.flink.runtime.state.hashmap.HashMapStateBackend;
import org.apache.flink.shaded.jackson2.com.fasterxml.jackson.databind.JsonNode;
import org.apache.flink.shaded.jackson2.com.fasterxml.jackson.databind.ObjectMapper;
import org.apache.flink.streaming.util.KeyedOneInputStreamOperatorTestHarness;
import org.apache.flink.table.data.GenericRowData;
import org.apache.flink.table.types.logical.BigIntType;
import org.apache.flink.table.types.logical.RowType;
import org.apache.flink.types.RowKind;
import org.junit.jupiter.api.extension.ExtendWith;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import tech.streamfusion.Native;
import tech.streamfusion.state.RocksDBNativeStateBackendFactory;

/** Actual JNI/columnar execution against immutable traces generated by released stock Flink. */
@ExtendWith(CoalescingOff.class)
class RetractingRankNativeCheckpointTest {
  private static final RowType INPUT =
      RowType.of(new BigIntType(), new BigIntType(), new BigIntType());
  private static final RowType OUTPUT =
      RowType.of(new BigIntType(), new BigIntType(), new BigIntType(), new BigIntType());
  private static final ObjectMapper JSON = new ObjectMapper();

  static Stream<Arguments> traces() {
    return Stream.of("offset", "missing", "empty", "ttl", "ttl-offset", "bound", "bound-ttl")
        .flatMap(
            shape ->
                Stream.of("heap", "rocks")
                    .flatMap(
                        store ->
                            Stream.of("hidden", "rank")
                                .flatMap(
                                    rank ->
                                        Stream.of(false, true)
                                            .map(
                                                every ->
                                                    Arguments.of(
                                                        shape + "-" + store + "-" + rank,
                                                        every)))));
  }

  @ParameterizedTest(name = "{0}, checkpoint-every-record={1}")
  @MethodSource("traces")
  void exactChangelogsSurviveProductionNativeCheckpointRecovery(String name, boolean every)
      throws Exception {
    JsonNode trace;
    try (var source = getClass().getResourceAsStream("/retracting-rank/" + name + ".json")) {
      assertNotNull(source, name);
      trace = JSON.readTree(source);
    }
    assertEquals("2.2.1", trace.path("flink_version").asText());
    boolean rank = trace.path("output_rank").asBoolean();
    var harness = harness(trace, null);
    try {
      int index = 0;
      for (JsonNode step : trace.path("steps")) {
        var fields = step.path("input").path("fields");
        var row =
            GenericRowData.of(
                fields.get(0).asLong(), fields.get(1).asLong(), fields.get(2).asLong());
        row.setRowKind(RowKind.fromByteValue((byte) step.path("input").path("kind").asInt()));
        long now = step.path("now").asLong();
        CanonicalAppendRankTypedTest.time(harness, now);
        harness.processElement(
            new org.apache.flink.streaming.runtime.streamrecord.StreamRecord<>(
                new ArrowBatch(
                    RowDataArrowConverter.write(
                        List.of(row), INPUT, NativeAllocator.SHARED, true))));
        harness.prepareSnapshotPreBarrier(0);
        var changes = CanonicalAppendRankTypedTest.collect(harness, rank ? OUTPUT : INPUT);
        var actual = new ArrayList<Object>();
        for (var change : changes) {
          var values = new ArrayList<Long>();
          for (int column = 0; column < (rank ? 4 : 3); column++)
            values.add(change.getLong(column));
          actual.add(java.util.Map.of("kind", change.getRowKind().toByteValue(), "fields", values));
        }
        assertEquals(
            step.path("output"),
            JSON.readTree(JSON.writeValueAsBytes(actual)),
            name + " step " + index);
        index++;
        if (every || index == trace.path("restore_after").asInt()) {
          var snapshot = harness.snapshot(index, now);
          harness.close();
          harness = null;
          harness = harness(trace, snapshot);
          assertTrue(harness.getOutput().isEmpty(), "Recovery must not re-emit retained rows");
          // A second checkpoint with no new input also retains count-only and bound-only keys.
          var noInput = harness.snapshot(index + 1000, now);
          harness.close();
          harness = null;
          harness = harness(trace, noInput);
          assertTrue(harness.getOutput().isEmpty());
        }
      }
    } finally {
      if (harness != null) harness.close();
    }
  }

  private static KeyedOneInputStreamOperatorTestHarness<Integer, ArrowBatch, ArrowBatch> harness(
      JsonNode trace, OperatorSubtaskState snapshot) throws Exception {
    boolean variable = trace.path("variable_bound").asBoolean();
    var operator =
        new NativeColumnarTopNOperator(
            new int[] {0},
            new int[] {-1},
            INPUT,
            new int[] {1},
            new int[] {1},
            new int[] {1},
            trace.path("rank_start").asLong() - 1,
            trace.path("rank_end").asLong(),
            trace.path("output_rank").asBoolean(),
            true,
            null,
            null,
            true,
            false,
            -1,
            trace.path("ttl_ms").asLong(),
            128,
            variable ? 2 : -1,
            variable) {
          @Override
          protected void configureStateHandle() {
            super.configureStateHandle();
            Native.enableStockRetractingTopNState(handle, directRocksDBState());
          }
        };
    var harness =
        new KeyedOneInputStreamOperatorTestHarness<Integer, ArrowBatch, ArrowBatch>(
            operator, ignored -> 0, Types.INT, 128, 1, 0);
    try {
      harness.setStateBackend(
          trace.path("serializes_values").asBoolean()
              ? new RocksDBNativeStateBackendFactory()
                  .createFromConfig(
                      new org.apache.flink.configuration.Configuration(),
                      RetractingRankNativeCheckpointTest.class.getClassLoader())
              : new HashMapStateBackend());
      harness.setup(new ArrowBatchSerializer());
      if (snapshot != null) harness.initializeState(snapshot);
      harness.open();
      return harness;
    } catch (Throwable failure) {
      try {
        harness.close();
      } catch (Throwable cleanup) {
        failure.addSuppressed(cleanup);
      }
      throw failure;
    }
  }
}
